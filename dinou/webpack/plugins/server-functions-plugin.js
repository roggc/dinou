import path from "node:path";
import fs from "node:fs";
import manifestGeneratorPlugin from "./manifest-generator-plugin.js";
import parseExports from "../../core/parse-exports.js";
import { useServerRegex } from "../../constants.js";
import { extractServerFunctions, hasServerFunctions } from "../../core/transform-server-functions.js";

class WebpackServerFunctionsPluginSimple {
  constructor(options = {}) {
    this.serverFunctions = new Map();
    this.serverFiles = options.serverFiles || null;
  }

  apply(compiler) {
    const { webpack } = compiler;
    const { Compilation, sources } = webpack;

    // Collect files generated by the loader
    compiler.hooks.thisCompilation.tap(
      "WebpackServerFunctionsPluginSimple",
      (compilation) => {
        compilation.hooks.processAssets.tap(
          {
            name: "WebpackServerFunctionsPluginSimple",
            stage: Compilation.PROCESS_ASSETS_STAGE_REPORT,
          },
          (assets) => {
            // 1. Collect all server function files generated by loader
            const serverFunctionsManifest = {};
            const serverFunctionPaths = new Set();

            for (const [filename, asset] of Object.entries(assets)) {
              if (
                filename.startsWith("server-functions/") &&
                filename.endsWith(".json")
              ) {
                try {
                  const content = asset.source();
                  const entry = JSON.parse(content);
                  serverFunctionsManifest[entry.path] = entry.exports;
                  serverFunctionPaths.add(
                    path.resolve(process.cwd(), entry.path).replace(/\\/g, "/").toLowerCase()
                  );

                  // Delete this temporary file
                  delete assets[filename];
                } catch (e) {
                  // Ignore parsing errors
                }
              }
            }

            if (this.serverFiles && this.serverFiles.size > 0) {
              for (const filePath of this.serverFiles) {
                const rel = path.relative(process.cwd(), filePath).replace(/\\/g, "/");
                if (!serverFunctionsManifest[rel]) {
                  try {
                    const fileCode = fs.readFileSync(filePath, "utf8");
                    if (useServerRegex.test(fileCode.trim())) {
                      const exports = parseExports(fileCode);
                      if (exports && exports.length > 0) {
                        serverFunctionsManifest[rel] = exports;
                        serverFunctionPaths.add(
                          path.resolve(process.cwd(), rel).replace(/\\/g, "/").toLowerCase()
                        );
                      }
                    } else if (hasServerFunctions(fileCode)) {
                      const actions = extractServerFunctions(fileCode, filePath);
                      if (actions && actions.length > 0) {
                        serverFunctionsManifest[rel] = actions;
                        serverFunctionPaths.add(
                          path.resolve(process.cwd(), rel).replace(/\\/g, "/").toLowerCase()
                        );
                      }
                    }
                  } catch (e) {}
                }
              }
            }

            // 2. Generate final manifest
            const manifestContent = JSON.stringify(
              serverFunctionsManifest,
              null,
              2
            );
            compilation.emitAsset(
              "server-functions-manifest.json",
              new sources.RawSource(manifestContent)
            );

            // 3. If no server functions exist in this compilation, do not touch any assets
            if (serverFunctionPaths.size === 0) {
              return;
            }

            // 4. Identify ONLY chunks that actually bundle a server function module
            const targetAssetFiles = new Set();

            for (const chunk of compilation.chunks) {
              let chunkModules = [];
              try {
                chunkModules = compilation.chunkGraph
                  ? compilation.chunkGraph.getChunkModules(chunk)
                  : (chunk.getModules ? chunk.getModules() : []);
              } catch (e) {
                chunkModules = [];
              }

              let containsServerFunction = false;
              for (const mod of chunkModules) {
                if (mod.resource) {
                  const norm = path.resolve(mod.resource).replace(/\\/g, "/").toLowerCase();
                  if (serverFunctionPaths.has(norm)) {
                    containsServerFunction = true;
                    break;
                  }
                }
                if (mod.modules) {
                  for (const sub of mod.modules) {
                    if (sub.resource) {
                      const normSub = path.resolve(sub.resource).replace(/\\/g, "/").toLowerCase();
                      if (serverFunctionPaths.has(normSub)) {
                        containsServerFunction = true;
                        break;
                      }
                    }
                  }
                }
                if (containsServerFunction) break;
              }

              if (containsServerFunction) {
                for (const file of chunk.files) {
                  targetAssetFiles.add(file);
                }
              }
            }

            // 5. Replace placeholder ONLY in chunks that actually contain server functions
            const isProd =
              process.env.NODE_ENV === "production" &&
              process.env.DINOU_DEV !== "true";
            const manifest = manifestGeneratorPlugin.manifestData;
            const proxyName = manifest["serverFunctionProxy.js"];
            if (isProd && !proxyName) {
              throw new Error(
                "[Dinou] webpack serverFunctionsPlugin: could not find hashed 'serverFunctionProxy.js' in manifest during production build."
              );
            }
            const hashedPath = proxyName || "serverFunctionProxy.js";

            for (const filename of targetAssetFiles) {
              if (filename.endsWith(".js") && assets[filename]) {
                let code = assets[filename].source();
                if (typeof code !== "string") {
                  code = code.toString("utf8");
                }
                if (code.includes("__SERVER_FUNCTION_PROXY__")) {
                  code = code.replace(/__SERVER_FUNCTION_PROXY__/g, hashedPath);
                  compilation.updateAsset(
                    filename,
                    new sources.RawSource(code)
                  );
                }
              }
            }
          }
        );
      }
    );
  }
}

export { WebpackServerFunctionsPluginSimple };
export default WebpackServerFunctionsPluginSimple;
