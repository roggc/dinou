const fs = require("fs");
const path = require("path");
const parseExports = require("./parse-exports.js");

function collectSourceFiles(dir, baseDir = dir) {
  if (!fs.existsSync(dir)) return [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  let files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files = files.concat(collectSourceFiles(fullPath, baseDir));
    } else if (/\.[jt]sx?$/.test(entry.name) && !entry.name.endsWith(".d.ts")) {
      const relPath = path.relative(baseDir, fullPath).replace(/\\/g, "/");
      files.push({
        relPath: "src/" + relPath,
        fullPath: fullPath.replace(/\\/g, "/"),
      });
    }
  }
  return files;
}

/**
 * Generates JS code that registers all src/ modules into globalThis.__DINOU_ROUTE_MODULES__
 * and their metadata (such as PPR support) into globalThis.__DINOU_ROUTE_METADATA__.
 * @param {string} projectRoot Root directory of the project
 * @param {string} relativeImportBase Relative path from generated output file to projectRoot
 * @returns {string} JavaScript code
 */
function generateRouteModulesCode(projectRoot = process.cwd(), relativeImportBase = "../..") {
  const srcDir = path.resolve(projectRoot, "src");
  const files = collectSourceFiles(srcDir);

  const configFilenames = ["dinou.config.js", "dinou.config.mjs", "dinou.config.cjs", "dinou.config.ts"];
  let foundConfig = null;
  for (const cf of configFilenames) {
    if (fs.existsSync(path.resolve(projectRoot, cf))) {
      foundConfig = cf;
      break;
    }
  }

  const lines = [
    "// Auto-generated by Dinou Route Generator for Edge/Workers bundling",
  ];

  if (foundConfig) {
    const configImportPath = `${relativeImportBase}/${foundConfig}`.replace(/\/+/g, "/");
    lines.push(`import dinouConfigModule from ${JSON.stringify(configImportPath)};`);
  }

  lines.push("export const routeModules = {");

  const routeMetadata = {};

  for (const file of files) {
    const importPath = `${relativeImportBase}/${file.relPath}`.replace(/\/+/g, "/");
    lines.push(`  ${JSON.stringify(file.relPath)}: () => import(${JSON.stringify(importPath)}),`);

    // Detect PPR from page_functions or layout_functions ONLY
    if (/(?:^|\/)(?:page_functions|layout_functions|page\.functions|layout\.functions)\.[jt]sx?$/.test(file.relPath)) {
      try {
        const content = fs.readFileSync(file.fullPath, "utf8");
        const isPpr = parseExports.parsePprConfig ? parseExports.parsePprConfig(content) : null;
        if (isPpr !== null) {
          routeMetadata[file.relPath] = { ppr: Boolean(isPpr) };
        }
      } catch (e) {}
    }
  }

  lines.push("};");
  lines.push("");
  lines.push("export const routeMetadata = " + JSON.stringify(routeMetadata, null, 2) + ";");
  lines.push("");
  lines.push("if (typeof globalThis !== 'undefined') {");
  lines.push("  globalThis.__DINOU_ROUTE_MODULES__ = {");
  lines.push("    ...(globalThis.__DINOU_ROUTE_MODULES__ || {}),");
  lines.push("    ...routeModules,");
  lines.push("  };");
  lines.push("  globalThis.__DINOU_ROUTE_METADATA__ = {");
  lines.push("    ...(globalThis.__DINOU_ROUTE_METADATA__ || {}),");
  lines.push("    ...routeMetadata,");
  lines.push("  };");
  if (foundConfig) {
    lines.push("  const resolvedConfig = (dinouConfigModule && dinouConfigModule.default) ? dinouConfigModule.default : dinouConfigModule;");
    lines.push("  globalThis.__DINOU_CONFIG__ = resolvedConfig;");
  }
  lines.push("}");
  lines.push("");
  if (foundConfig) {
    lines.push("export const dinouConfig = (dinouConfigModule && dinouConfigModule.default) ? dinouConfigModule.default : dinouConfigModule;");
  }
  lines.push("export default routeModules;");

  return lines.join("\n");
}

module.exports = {
  collectSourceFiles,
  generateRouteModulesCode,
};
